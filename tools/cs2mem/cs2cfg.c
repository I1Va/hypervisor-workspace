#include "cs2cfg.h"

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

void cs2_offsets_clear(cs2_offsets *o)
{
	memset(o, 0, sizeof(*o));
}

/* "0x1a2b" or "6699" or decimal. Returns 0 on success. */
static int parse_num(const char *s, uint64_t *out)
{
	char *end = NULL;

	while (isspace((unsigned char)*s))
		s++;
	if (*s == '\0')
		return 1;
	*out = strtoull(s, &end, 0);
	if (end == s)
		return 1;
	while (isspace((unsigned char)*end))
		end++;
	if (*end != '\0')
		return 1;
	return 0;
}

typedef struct field
{
	const char *name;
	size_t      offset;
	size_t      size;      /* 8 for uint64/uint32 pairs, 65 for the hash string */
	int         zero_ok;   /* zero is a meaningful value, not "unset" */
} field;

#define F(n) { #n, offsetof(cs2_offsets, n), sizeof(((cs2_offsets *)0)->n), 0 }

static const field FIELDS[] = {
	F(dw_entity_system),
	F(off_entity_list),
	F(off_highest_index),
	F(chunk_stride),
	F(chunk_entities),
	/*
	 * 0 is meaningful here: it selects the by-value chunk layout. So presence,
	 * not value, is what the completeness check tests for this one.
	 */
	{ "off_identity_entity", offsetof(cs2_offsets, off_identity_entity),
	  sizeof(((cs2_offsets *)0)->off_identity_entity), 1 },
	F(off_health),
	F(off_team),
	F(off_origin),
	F(off_lifestate),
	F(off_weapon_services),
	F(off_pawn_handle),
	F(off_is_alive),
	F(off_handle_serial),
};

/* Which fields the loaded file actually contained. */
static unsigned seen_mask;

static uint64_t field_value(const cs2_offsets *o, const field *f)
{
	if (f->size == 8)
		return *(const uint64_t *)((const char *)o + f->offset);
	return *(const uint32_t *)((const char *)o + f->offset);
}

int cs2_offsets_load(cs2_offsets *o, const char *path, char *err, size_t err_cap)
{
	FILE *f;
	char line[512];
	int lineno = 0;

	cs2_offsets_clear(o);
	seen_mask = 0;

	f = fopen(path, "r");
	if (f == NULL) {
		snprintf(err, err_cap, "cannot open %s", path);
		return 1;
	}

	while (fgets(line, sizeof(line), f) != NULL) {
		char *eq, *key, *val, *hash;
		lineno++;

		/* Strip comment and trailing whitespace. */
		hash = strchr(line, '#');
		if (hash != NULL)
			*hash = '\0';
		eq = strchr(line, '=');
		if (eq == NULL) {
			/* Blank or comment-only line. */
			if (strspn(line, " \t\r\n") == strlen(line))
				continue;
			snprintf(err, err_cap, "%s:%d: expected key=value", path, lineno);
			fclose(f);
			return 1;
		}

		*eq = '\0';
		key = line;
		val = eq + 1;

		while (isspace((unsigned char)*key))
			key++;
		{
			char *e = key + strlen(key);
			while (e > key && isspace((unsigned char)e[-1]))
				*--e = '\0';
		}
		while (isspace((unsigned char)*val))
			val++;
		{
			char *e = val + strlen(val);
			while (e > val && isspace((unsigned char)e[-1]))
				*--e = '\0';
		}

		if (strcmp(key, "client_sha256") == 0) {
			if (strlen(val) != 64) {
				snprintf(err, err_cap, "%s:%d: client_sha256 must be 64 hex chars",
					 path, lineno);
				fclose(f);
				return 1;
			}
			memcpy(o->client_sha256, val, 64);
			o->client_sha256[64] = '\0';
			continue;
		}

		{
			size_t i;
			int found = 0;
			for (i = 0; i < sizeof(FIELDS) / sizeof(FIELDS[0]); i++) {
				uint64_t v;
				if (strcmp(key, FIELDS[i].name) != 0)
					continue;
				if (parse_num(val, &v) != 0) {
					snprintf(err, err_cap, "%s:%d: %s is not a number: %s",
						 path, lineno, key, val);
					fclose(f);
					return 1;
				}
				if (FIELDS[i].size == 8)
					*(uint64_t *)((char *)o + FIELDS[i].offset) = v;
				else
					*(uint32_t *)((char *)o + FIELDS[i].offset) = (uint32_t)v;
				seen_mask |= 1u << i;
				found = 1;
				break;
			}
			if (!found) {
				/*
				 * Refusing unknown keys is deliberate. A typo such as
				 * off_heath=0x340 would otherwise be ignored and the reader
				 * would read offset 0 for ever, returning a valid-looking
				 * health of whatever happens to live at the entity base.
				 */
				snprintf(err, err_cap, "%s:%d: unknown offset %s", path, lineno, key);
				fclose(f);
				return 1;
			}
		}
	}
	fclose(f);
	return 0;
}

int cs2_offsets_save(const cs2_offsets *o, const char *path)
{
	FILE *f = fopen(path, "w");
	size_t i;

	if (f == NULL)
		return 1;

	fprintf(f, "# cs2mem offsets - generated by `cs2mem discover`\n");
	fprintf(f, "# client_sha256 pins these to one client.dll build.\n");
	fprintf(f, "client_sha256=%s\n", o->client_sha256);
	for (i = 0; i < sizeof(FIELDS) / sizeof(FIELDS[0]); i++) {
		if (FIELDS[i].size == 8)
			fprintf(f, "%s=0x%llx\n", FIELDS[i].name,
				(unsigned long long)*(uint64_t *)((const char *)o + FIELDS[i].offset));
		else
			fprintf(f, "%s=0x%x\n", FIELDS[i].name,
				*(uint32_t *)((const char *)o + FIELDS[i].offset));
	}
	fclose(f);
	return 0;
}

int cs2_offsets_complete(const cs2_offsets *o)
{
	size_t i;

	if (o->client_sha256[0] == '\0')
		return 0;

	for (i = 0; i < sizeof(FIELDS) / sizeof(FIELDS[0]); i++) {
		/*
		 * Presence first, then value. A field that was never in the file is
		 * unset even if the struct byte happens to be non-zero; a field whose
		 * zero is meaningful (off_identity_entity) is valid once present.
		 */
		if ((seen_mask & (1u << i)) == 0)
			return 0;
		if (!FIELDS[i].zero_ok && field_value(o, &FIELDS[i]) == 0)
			return 0;
	}
	return 1;
}
